// Writes src/styles/palette.css: one CSS custom property per Tailwind colour shade the app can use,
// for light and dark. tailwind.config.js points every one of those shades at its property, so a class
// such as bg-emerald-50 or text-rose-700 follows the theme without a per-class dark override.
//
// Light is Tailwind's own value. Dark keeps the hue and re-steps it: tints (50-300) become washes of the
// 500 mixed into the dark surface, 400-600 stay saturated for marks and dots, and the text shades
// (700-950) become the light end of the scale so they read on a dark ground.
//
// Run from frontend/: node scripts/gen-palette.mjs
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const colors = require("tailwindcss/colors");
const { FAMILIES, SHADES } = require("./palette-families.cjs");
const here = path.dirname(fileURLToPath(import.meta.url));

const SURFACE = [24, 24, 27]; // the dark raised surface most tints sit on
const DARK = { 50: ["500", 0.86], 100: ["500", 0.8], 200: ["500", 0.62], 300: ["500", 0.45], 400: ["400", 0.06], 500: ["500", 0], 600: ["500", 0], 700: ["300", 0], 800: ["200", 0], 900: ["100", 0], 950: ["50", 0] };

const rgb = (hex) => [1, 3, 5].map((index) => parseInt(hex.slice(index, index + 2), 16));
const mix = (a, b, t) => a.map((value, index) => Math.round(value * (1 - t) + b[index] * t));
const channels = (value) => value.join(" ");

const light = []; const dark = [];
for (const family of FAMILIES) {
  for (const shade of SHADES) {
    light.push(`  --tw-${family}-${shade}: ${channels(rgb(colors[family][shade]))};`);
    const [source, amount] = DARK[shade];
    dark.push(`  --tw-${family}-${shade}: ${channels(mix(rgb(colors[family][source]), SURFACE, amount))};`);
  }
}
const css = `/* Generated by scripts/gen-palette.cjs. Do not edit by hand. */\n:root {\n${light.join("\n")}\n}\n\n:root[data-theme="dark"] {\n${dark.join("\n")}\n}\n`;
fs.writeFileSync(path.join(here, "..", "src", "styles", "palette.css"), css);
console.log(`palette.css: ${FAMILIES.length} families × ${SHADES.length} shades`);
